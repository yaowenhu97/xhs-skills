def scan_text(text):
    out = {}
    for name, words in GROUPS:
        hits = sorted({w for w in words if w in text})
        if hits:
            out[name] = hits
    n = len(BARE.findall(text))
    if n:
        out['裸「最」'] = [f'共{n}处']
    for label, pat in CONTACT.items():
        got = sorted({m.group() for m in pat.finditer(text)})
        if got:
            out.setdefault('导流', []).extend(f'{label}:{g}' for g in got)
    return out


def iter_files(targets):
    for t in targets:
        if os.path.isdir(t):
            for f in sorted(os.listdir(t)):
                if f.lower().endswith(('.md', '.txt')):
                    yield os.path.join(t, f)
        elif os.path.isfile(t):
            yield t


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if not args:
        print(__doc__)
        return
    total = hit = 0
    for p in iter_files(args):
        total += 1
        try:
            text = open(p, encoding='utf-8').read()
        except UnicodeDecodeError:
            text = open(p, encoding='gbk', errors='ignore').read()
        h = scan_text(text)
        if h:
            hit += 1
            print(f'[平台规则] {p}')
            for k in sorted(h):
                print(f'    {k}: {h[k]}')
    print(f'\n共 {total} 个文件 | 命中 {hit} 个')


if __name__ == '__main__':
    main()
